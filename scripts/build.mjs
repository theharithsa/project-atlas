import {copyFile, mkdir, readFile, writeFile} from 'node:fs/promises';
import {createElement as h} from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {Badge} from '@astryxdesign/core/Badge';
import {Button} from '@astryxdesign/core/Button';
import {Theme} from '@astryxdesign/core/theme';
import {neutralTheme} from '@astryxdesign/theme-neutral/built';

const generated = new URL('../site/generated/', import.meta.url);
const dependencies = new URL('../node_modules/', import.meta.url);
const output = name => new URL(name, generated);
const dependency = name => new URL(name, dependencies);
const read = url => readFile(url, 'utf8');
const packageFile = name => new URL(import.meta.resolve(name));

const templates = {
  activity: h(Button, {label:'Explore activity', href:'#ATLAS_ACTIVITY_HREF', variant:'primary', className:'console-cta'}),
  developer: h(Button, {label:'View activity', type:'submit', variant:'primary', size:'sm'}),
  share: h(Button, {label:'Share view', id:'share-view', variant:'secondary', size:'sm'}),
  saveOwners: h(Button, {label:'Save and view my portfolio', type:'submit', variant:'primary', size:'sm'}),
  done: h(Badge, {label:'ATLAS_LABEL', variant:'success'}),
  pending: h(Badge, {label:'ATLAS_LABEL', variant:'warning'}),
  planned: h(Badge, {label:'ATLAS_LABEL', variant:'info'}),
  unassigned: h(Badge, {label:'ATLAS_LABEL'}),
};

// Use Astryx's HTML and compiled styles. Atlas keeps its existing native forms and navigation.
const html = Object.fromEntries(Object.entries(templates).map(([key, component]) => {
  const markup = renderToStaticMarkup(h(Theme, {theme:neutralTheme, mode:'dark'}, component));
  return [key, markup.slice(markup.indexOf('>') + 1, markup.lastIndexOf('</div>'))];
}));
const css = await Promise.all([
  read(packageFile('@astryxdesign/core/astryx.css')),
  read(packageFile('@astryxdesign/theme-neutral/theme.css')),
]);
const fonts = ['space-grotesk', 'jetbrains-mono'];
const licenses = await Promise.all([
  read(dependency('@astryxdesign/theme-neutral/LICENSE')).then(s => 'Astryx core and Neutral theme\n\n' + s),
  ...fonts.map(name => read(dependency('@fontsource-variable/' + name + '/LICENSE')).then(s => name + '\n\n' + s)),
]);
await mkdir(generated,{recursive:true});
await Promise.all([
  writeFile(output('astryx.css'),css.join('\n')),
  writeFile(output('controls.js'),'// Generated by scripts/build.mjs.\nexport const controls = ' + JSON.stringify(html,null,2) + ';\n'),
  writeFile(output('licenses.txt'),licenses.join('\n\n')),
  ...fonts.map(name => copyFile(dependency('@fontsource-variable/' + name + '/files/' + name + '-latin-wght-normal.woff2'),output(name + '.woff2'))),
]);
